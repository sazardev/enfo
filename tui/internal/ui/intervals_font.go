var intervalsFold = strings.NewReplacer("Á", "A", "É", "E", "Í", "I", "Ó", "O", "Ú", "U", "Ü", "U", "Ñ", "N")

// intervalsWordSize returns the pixel pitch that fits word into maxW x maxH
// dots (0 when even the smallest does not fit).
func intervalsWordSize(word string, maxW, maxH int) int {
	n := len([]rune(word))
	if n == 0 {
		return 0
	}
	for p := 8; p >= 1; p-- {
		if (6*n-1)*p <= maxW && 7*p <= maxH {
			return p
		}
	}
	return 0
}

// intervalsDrawWord draws word centered at cx, cy with pixel pitch p.
func intervalsDrawWord(c *braille.Canvas, word string, cx, cy float64, p int, col braille.RGB) {
	word = intervalsFold.Replace(strings.ToUpper(word))
	rs := []rune(word)
	if len(rs) == 0 || p < 1 {
		return
	}
	total := (6*len(rs) - 1) * p
	x0 := cx - float64(total)/2
	y0 := cy - float64(7*p)/2
	for i, r := range rs {
		bm, ok := intervalsLetters[r]
		if !ok {
			continue
		}
		for row, line := range bm {
			for colI, ch := range line {
				if ch != '#' {
					continue
				}
				px := int(x0) + (i*6+colI)*p
				py := int(y0) + row*p
				switch {
				case p == 1:
					c.Set(px, py, col)
				case p == 2:
					c.Set(px, py, col)
					c.Set(px+1, py, col)
					c.Set(px, py+1, col)
					c.Set(px+1, py+1, col)
				default:
					c.RoundRect(float64(px), float64(py), float64(p-1), float64(p-1), float64(p)*0.3, braille.Solid(col))
				}
			}
		}
	}
}
